def detect_system_language() -> str:
    try:
        sys_loc = locale.getlocale()[0] or locale.getdefaultlocale()[0] or ""
        short = sys_loc.split("_")[0].split("-")[0].lower()
        if short in LANGUAGES:
            return short
    except Exception:
        pass
    return "en"


def set_language(lang_code: str) -> str:
    global _CURRENT_LANG
    code = (lang_code or "").lower().strip()
    if code not in LANGUAGES:
        code = "en"
    _CURRENT_LANG = code
    return _CURRENT_LANG


def get_language() -> str:
    return _CURRENT_LANG


def tr(key: str, **kwargs) -> str:
    lang_dict = TRANSLATIONS.get(_CURRENT_LANG, TRANSLATIONS["en"])
    text = lang_dict.get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text